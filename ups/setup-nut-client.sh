#!/usr/bin/env bash
# setup-nut-client.sh — make this Mac shut down cleanly when the UPS (attached to the NAS) runs low.
#
# The NAS (UGOS) is the NUT server: UPS name "ups0", user "nut", listening on port 3493.
# This Mac runs upsmon as a NUT *secondary*: when the NAS signals low battery / forced shutdown,
# this Mac powers off first, then the NAS.
#
# Usage:
#   ./ups/setup-nut-client.sh                 # prompts for NAS IP and NUT password
#   NAS_IP=192.168.1.50 ./ups/setup-nut-client.sh
#
# The password is written only to a root-only file on this machine — never to this repo.

set -euo pipefail

UPS_NAME="${UPS_NAME:-ups0}"
NUT_USER="${NUT_USER:-nut}"
PREFIX="$(brew --prefix)"
CONF_DIR="$PREFIX/etc/nut"
STATE_DIR="$PREFIX/var/state/ups"
PLIST=/Library/LaunchDaemons/local.nut.upsmon.plist

command -v upsmon >/dev/null || brew install nut

if [[ -z "${NAS_IP:-}" ]]; then
  read -r -p "NAS home-network IP (e.g. 192.168.1.x, not the Tailscale 100.x): " NAS_IP
fi
read -r -s -p "NUT password for user '$NUT_USER' (from /etc/nut/upsd.users on the NAS): " NUT_PASS; echo

echo "==> Checking the NAS answers..."
if ! upsc "${UPS_NAME}@${NAS_IP}" ups.status 2>/dev/null; then
  echo "!! Can't read ${UPS_NAME}@${NAS_IP}. Check the IP, that NUT Server is enabled in UGOS, and port 3493." >&2
  exit 1
fi

sudo -v
sudo mkdir -p "$CONF_DIR" "$STATE_DIR"

echo "==> Writing $CONF_DIR/nut.conf"
echo "MODE=netclient" | sudo tee "$CONF_DIR/nut.conf" >/dev/null

echo "==> Writing $CONF_DIR/upsmon.conf (root-only)"
sudo tee "$CONF_DIR/upsmon.conf" >/dev/null <<EOF
# Generated by dotfiles/ups/setup-nut-client.sh — contains a password, do not commit.
RUN_AS_USER root
MONITOR ${UPS_NAME}@${NAS_IP} 1 ${NUT_USER} ${NUT_PASS} secondary
MINSUPPLIES 1
SHUTDOWNCMD "/sbin/shutdown -h +0"
POLLFREQ 5
POLLFREQALERT 5
DEADTIME 25
HOSTSYNC 15
FINALDELAY 5
POWERDOWNFLAG ${STATE_DIR}/killpower
EOF
sudo chown root:wheel "$CONF_DIR/upsmon.conf" "$CONF_DIR/nut.conf"
sudo chmod 600 "$CONF_DIR/upsmon.conf"

echo "==> Installing launchd job $PLIST"
sudo tee "$PLIST" >/dev/null <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>local.nut.upsmon</string>
  <key>ProgramArguments</key>
  <array>
    <string>${PREFIX}/sbin/upsmon</string>
  </array>
  <key>RunAtLoad</key><true/>
  <key>AbandonProcessGroup</key><true/>
  <key>StandardOutPath</key><string>/var/log/nut-upsmon.log</string>
  <key>StandardErrorPath</key><string>/var/log/nut-upsmon.log</string>
</dict>
</plist>
EOF
sudo chown root:wheel "$PLIST"; sudo chmod 644 "$PLIST"
sudo launchctl bootout system "$PLIST" 2>/dev/null || true
sudo pkill -x upsmon 2>/dev/null || true
sudo launchctl bootstrap system "$PLIST"

sleep 3
if pgrep -x upsmon >/dev/null; then
  echo "==> upsmon is running."
  echo "    Status:  upsc ${UPS_NAME}@${NAS_IP} ups.status   (OL = on line power, OB = on battery, LB = low battery)"
  echo "    Logs:    tail -f /var/log/nut-upsmon.log"
else
  echo "!! upsmon didn't stay running — check /var/log/nut-upsmon.log" >&2
  exit 1
fi
